//! Generates the Vulkan FFI declarations from the registry at build time.

use std::error::Error;
use std::io::Write;
use std::path::PathBuf;

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo::rerun-if-changed=../codegen/vk.xml");
    println!("cargo::rerun-if-changed=../codegen/src/");
    println!("cargo::rerun-if-changed=build.rs");

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("Cargo sets OUT_DIR"));
    let vk_xml = codegen::VkXml::from("../codegen/vk.xml")?;

    let mut declarations = Vec::new();
    writeln!(declarations, "// Autogenerated source file.")?;
    vk_xml.write_decls(&mut declarations)?;
    std::fs::write(out_dir.join("codegen_vk_decls.rs"), declarations)?;

    Ok(())
}
