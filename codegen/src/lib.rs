    fn writes_dispatch_tables() {
        let vk_xml = vk_xml();
        let extensions: Vec<&str> = policy::INSTANCE_EXTENSIONS
            .iter()
            .chain(policy::DEVICE_EXTENSIONS)
            .copied()
            .collect();
        let options = DispatchOptions {
            extensions: &extensions,
            loader_commands: policy::LOADER_COMMANDS,
            instance_commands: policy::INSTANCE_COMMANDS,
        };
        let mut output = Vec::new();
        vk_xml
            .write_dispatch_tables(&mut output, &options, &HashSet::new())
            .expect("dispatch tables emit");
        let output = String::from_utf8(output).expect("generated source is UTF-8");
        assert!(output.contains("pub fn instance_command"));
        assert!(output.contains("pub fn device_command"));
        assert!(output.contains(r#""vkCreateInstance" => vkCreateInstance"#));
        assert!(output.contains(r#""vkGetDeviceProcAddr" => vkGetDeviceProcAddr"#));
        assert!(output.contains(r#""vkCreateSwapchainKHR" => vkCreateSwapchainKHR"#));
        assert!(output.contains(
            r#""vkGetPhysicalDeviceToolPropertiesEXT" => vkGetPhysicalDeviceToolProperties"#
        ));
        assert!(!output.contains(r#""vkGetInstanceProcAddr""#));
        assert!(output.contains("pub type PFN_vkCreateInstance = Option<unsafe extern \"C\" fn("));
        assert!(output.contains("let _: PFN_vkCreateInstance = Some(vkCreateInstance);"));
        assert!(output.contains(
            "pub type PFN_vkCmdSetBlendConstants = Option<unsafe extern \"C\" fn(VkCommandBuffer, *const f32)>;"
        ));
        assert!(output.contains(
            "pub type PFN_vkCreateSwapchainKHR = Option<unsafe extern \"C\" fn(VkDevice, Option<NonNull<VkSwapchainCreateInfoKHR>>, Option<NonNull<VkAllocationCallbacks>>, Option<NonNull<VkSwapchainKHR>>) -> VkResult>;"
        ));
        assert!(output.contains(
            "pub type PFN_vkMapMemory = Option<unsafe extern \"C\" fn(VkDevice, VkDeviceMemory, VkDeviceSize, VkDeviceSize, VkMemoryMapFlags, Option<NonNull<NonNull<std::ffi::c_void>>>) -> VkResult>;"
        ));
        assert!(output.contains(
            "pub unsafe extern \"C\" fn vkCreateInstance(_: Option<NonNull<VkInstanceCreateInfo>>, _: Option<NonNull<VkAllocationCallbacks>>, _: Option<NonNull<VkInstance>>) -> VkResult"
        ));
        assert!(output.contains("unimplemented!(\"vkCreateInstance\")"));
        assert!(!output.contains("fn vkGetPhysicalDeviceToolPropertiesEXT("));
        assert!(!output.contains("fn vkCreateHeadlessSurfaceEXT("));

        let mut stub_count = 0;
        for line in output.lines() {
            let Some(rest) = line.strip_prefix("pub unsafe extern \"C\" fn ") else {
                continue;
            };
            let name = rest.split('(').next().expect("stub has a name");
            assert!(
                output.contains(&format!("=> {name},")),
                "{name} is not a dispatch target"
            );
            stub_count += 1;
        }
        assert!(stub_count > 0);
    }

