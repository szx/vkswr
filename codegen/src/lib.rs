    #[test]
    fn writes_dispatch_tables() {
        let vk_xml = vk_xml();
        let options = DispatchOptions {
            extensions: &[
                "VK_KHR_surface",
                "VK_KHR_xcb_surface",
                "VK_KHR_swapchain",
                "VK_EXT_tooling_info",
                "VK_EXT_debug_marker",
            ],
            loader_commands: &["vkGetInstanceProcAddr"],
            instance_commands: &["vkGetDeviceProcAddr"],
        };
        let mut output = Vec::new();
        vk_xml
            .write_dispatch_tables(&mut output, &options)
            .expect("dispatch tables emit");
        let output = String::from_utf8(output).expect("generated source is UTF-8");
        assert!(output.contains("pub fn instance_command"));
        assert!(output.contains("pub fn device_command"));
        assert!(output.contains(r#""vkCreateInstance" => vkCreateInstance"#));
        assert!(output.contains(r#""vkGetDeviceProcAddr" => vkGetDeviceProcAddr"#));
        assert!(output.contains(r#""vkCreateSwapchainKHR" => vkCreateSwapchainKHR"#));
        assert!(output.contains(
            r#""vkGetPhysicalDeviceToolPropertiesEXT" => vkGetPhysicalDeviceToolProperties"#
        ));
        assert!(!output.contains(r#""vkGetInstanceProcAddr""#));
    }

    #[test]
    fn output_is_deterministic() {
        let vk_xml = vk_xml();
        let mut first = Vec::new();
        let mut second = Vec::new();
        vk_xml.write_decls(&mut first).expect("first emit");
        vk_xml.write_decls(&mut second).expect("second emit");
        assert_eq!(first, second);
    }
