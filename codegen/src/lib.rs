//! Generates Rust sources from the Vulkan registry (`vk.xml`).
//!
//! [`VkXml`] parses the registry once and emits either the Rust type
//! declarations used by the `headers` crate or the ICD dispatch tables used by
//! the `icd` crate.

mod vk_xml;

use std::collections::{BTreeSet, HashMap, HashSet};
use std::io::Write;
use std::sync::Arc;

use proc_macro2::{Literal, TokenStream};
use quote::{format_ident, quote};
use thiserror::Error;

pub use vk_xml::*;

impl VkXml {
    /// Writes the Vulkan type declarations as a Rust source file.
    ///
    /// # Errors
    ///
    /// Returns [`CodegenError`] if writing to `output` fails or the registry
    /// contains a value that cannot be represented in Rust.
    pub fn write_decls(&self, output: &mut impl Write) -> Result<(), CodegenError> {
        let mut emitter = Emitter::default();
        emitter.mark_seen("xcb_connection_t");
        emitter.mark_seen("xcb_window_t");

        emit_all(output, &mut emitter, &self.enums)?;
        emit_all(output, &mut emitter, self.structs_by_name())?;
        emit_all(output, &mut emitter, self.typedefs_by_name())?;
        emit_all(output, &mut emitter, self.type_attributes_by_name())?;
        emit_all(output, &mut emitter, self.type_externs_by_name())?;
        emit_all(output, &mut emitter, self.extensions_by_name())?;
        Ok(())
    }

    /// Writes the ICD dispatch tables derived from the registry.
    ///
    /// The generated file defines `instance_command` and `device_command`,
    /// which map Vulkan command names to ICD entry points. Commands come from
    /// Vulkan 1.0 plus the advertised extensions; loader-provided commands are
    /// excluded and aliases are resolved to their canonical implementation.
    ///
    /// Vulkan 1.0 stubs are included on purpose: the loader requires
    /// `vk_icdGetInstanceProcAddr` to return non-null for every core 1.0 entry
    /// point, even when the implementation is not complete yet.
    ///
    /// # Errors
    ///
    /// Returns [`CodegenError`] if writing to `output` fails or if an
    /// advertised extension or command is missing from the registry.
    pub fn write_dispatch_tables(
        &self,
        output: &mut impl Write,
        options: &DispatchOptions<'_>,
    ) -> Result<(), CodegenError> {
        let (instance, device) = self.dispatch_entries(options)?;
        writeln!(output, "// Autogenerated source file.")?;
        emit_dispatch_table(output, "instance", &instance)?;
        emit_dispatch_table(output, "device", &device)?;
        Ok(())
    }

    fn dispatch_entries<'a>(
        &'a self,
        options: &DispatchOptions<'_>,
    ) -> Result<DispatchEntries<'a>, CodegenError> {
        let mut selected: BTreeSet<&'a str> = BTreeSet::new();

        for feature in &self.extensions {
            let is_vulkan_1_0 = feature.number.as_ref() == "1.0"
                && feature
                    .api
                    .as_deref()
                    .is_some_and(|api| api.split(',').any(|api| api.trim() == "vulkan"));
            if is_vulkan_1_0 {
                selected.extend(feature.commands.iter().map(Arc::as_ref));
            }
        }

        for extension_name in options.extensions {
            let extension = self
                .extensions
                .iter()
                .find(|extension| extension.name.as_ref() == *extension_name)
                .ok_or_else(|| CodegenError::UnknownExtension((*extension_name).to_owned()))?;
            selected.extend(extension.commands.iter().map(Arc::as_ref));
        }

        for loader_command in options.loader_commands {
            selected.remove(*loader_command);
        }

        let commands: HashMap<&'a str, &'a VkCommand> = self
            .commands
            .iter()
            .map(|command| (command.name.as_ref(), command))
            .collect();

        let mut instance = Vec::new();
        let mut device = Vec::new();
        for name in selected {
            let canonical = canonical_command(&commands, name)?;
            let command = commands
                .get(canonical)
                .ok_or_else(|| CodegenError::UnknownCommand(canonical.to_owned()))?;
            if options.instance_commands.contains(&name) || command.is_instance_level() {
                instance.push((name, canonical));
            } else {
                device.push((name, canonical));
            }
        }

        Ok((instance, device))
    }

    fn structs_by_name(&self) -> Vec<&VkStruct> {
        sorted_by_name(&self.structs)
    }

    fn typedefs_by_name(&self) -> Vec<&VkTypedef> {
        sorted_by_name(&self.typedefs)
    }

    fn type_attributes_by_name(&self) -> Vec<&VkTypeAttributes> {
        sorted_by_name(&self.type_attributes)
    }

    fn type_externs_by_name(&self) -> Vec<&VkTypeExtern> {
        sorted_by_name(&self.type_externs)
    }

    fn extensions_by_name(&self) -> Vec<&VkExtension> {
        sorted_by_name(&self.extensions)
    }
}

/// Options for [`VkXml::write_dispatch_tables`].
#[derive(Debug, Clone, Copy)]
pub struct DispatchOptions<'a> {
    /// Extensions advertised by the ICD; all their commands are exposed.
    pub extensions: &'a [&'a str],
    /// Commands implemented by the Vulkan loader rather than the ICD.
    pub loader_commands: &'a [&'a str],
    /// Commands that must be resolved through the instance dispatch table even
    /// though their registry signature is device-level.
    pub instance_commands: &'a [&'a str],
}

type DispatchEntries<'a> = (Vec<(&'a str, &'a str)>, Vec<(&'a str, &'a str)>);

impl VkCommand {
    /// Whether the loader resolves this command through `vkGetInstanceProcAddr`.
    fn is_instance_level(&self) -> bool {
        !matches!(
            self.first_parameter_type.as_deref(),
            Some("VkDevice" | "VkQueue" | "VkCommandBuffer")
        )
    }
}

fn canonical_command<'a>(
    commands: &HashMap<&'a str, &'a VkCommand>,
    name: &'a str,
) -> Result<&'a str, CodegenError> {
    let mut current = name;
    let mut seen = HashSet::new();
    loop {
        if !seen.insert(current) {
            return Err(CodegenError::AliasCycle(name.to_owned()));
        }
        let Some(command) = commands.get(current) else {
            return Err(CodegenError::UnknownCommand(current.to_owned()));
        };
        match &command.alias {
            Some(alias) => current = alias.as_ref(),
            None => return Ok(current),
        }
    }
}

fn emit_dispatch_table(
    output: &mut impl Write,
    level: &str,
    entries: &[(&str, &str)],
) -> Result<(), CodegenError> {
    writeln!(
        output,
        "/// Resolves an {level}-level Vulkan command to its ICD entry point."
    )?;
    writeln!(
        output,
        "pub fn {level}_command(name: &str) -> PFN_vkVoidFunction {{"
    )?;
    writeln!(output, "    crate::dispatch!(name, {{")?;
    for (command, function) in entries {
        writeln!(output, "        {command:?} => {function},")?;
    }
    writeln!(output, "    }})")?;
    writeln!(output, "}}")?;
    writeln!(output)?;
    Ok(())
}

fn sorted_by_name<T: Named>(items: &HashSet<T>) -> Vec<&T> {
    let mut items: Vec<_> = items.iter().collect();
    items.sort_by_key(|item| item.name());
    items
}

fn emit_all<'a, T: Emit + 'a>(
    output: &mut impl Write,
    emitter: &mut Emitter,
    items: impl IntoIterator<Item = &'a T>,
) -> Result<(), CodegenError> {
    for item in items {
        writeln!(output, "{}", item.emit(emitter)?)?;
    }
    Ok(())
}

/// Errors produced while generating Rust source code from the registry.
#[derive(Debug, Error)]
pub enum CodegenError {
    #[error("failed to write generated source: {0}")]
    Io(#[from] std::io::Error),
    #[error("`{source}` is not a valid Rust type")]
    InvalidType {
        source: String,
        #[source]
        error: proc_macro2::LexError,
    },
    #[error("`{source}` is not a valid Rust literal")]
    InvalidLiteral {
        source: String,
        #[source]
        error: proc_macro2::LexError,
    },
    #[error("`{0}` is not a valid integer literal")]
    InvalidInteger(String),
    #[error("unsupported enum value `{0}`")]
    UnsupportedEnumValue(String),
    #[error("advertised extension `{0}` is not present in the registry")]
    UnknownExtension(String),
    #[error("command `{0}` is not present in the registry")]
    UnknownCommand(String),
    #[error("command alias cycle while resolving `{0}`")]
    AliasCycle(String),
}

impl CodegenError {
    fn invalid_type(source: impl Into<String>) -> impl FnOnce(proc_macro2::LexError) -> Self {
        let source = source.into();
        move |error| Self::InvalidType { source, error }
    }

    fn invalid_literal(source: impl Into<String>) -> impl FnOnce(proc_macro2::LexError) -> Self {
        let source = source.into();
        move |error| Self::InvalidLiteral { source, error }
    }
}

/// State shared while emitting a registry.
#[derive(Debug, Default)]
struct Emitter {
    /// Names already emitted, used to suppress duplicated extension constants.
    seen: HashSet<Arc<str>>,
    /// Type of each API constant, used to resolve aliases to their real type.
    api_constant_types: HashMap<Arc<str>, String>,
}

impl Emitter {
    /// Marks `name` as emitted, returning `true` if it had not been seen yet.
    fn mark_seen(&mut self, name: &str) -> bool {
        self.seen.insert(Arc::from(name))
    }

    fn mark_seen_arc(&mut self, name: &Arc<str>) -> bool {
        self.seen.insert(Arc::clone(name))
    }
}

/// A registry item that can be emitted as Rust tokens.
trait Emit {
    fn emit(&self, emitter: &mut Emitter) -> Result<TokenStream, CodegenError>;
}

/// A registry item with a stable name, used to sort generated output.
trait Named {
    fn name(&self) -> &str;
}

impl Named for VkStruct {
    fn name(&self) -> &str {
        match self {
            Self::Alias { name, .. } | Self::Struct { name, .. } | Self::Union { name, .. } => name,
        }
    }
}

impl Named for VkTypedef {
    fn name(&self) -> &str {
        match self {
            Self::Alias { name, .. } => name,
        }
    }
}

impl Named for VkTypeAttributes {
    fn name(&self) -> &str {
        match self {
            Self::Alias { name, .. } => name,
        }
    }
}

impl Named for VkTypeExtern {
    fn name(&self) -> &str {
        match self {
            Self::Extern { name } | Self::FuncPointer { name, .. } => name,
        }
    }
}

impl Named for VkExtension {
    fn name(&self) -> &str {
        &self.name
    }
}

fn rust_type(source: &str) -> Result<TokenStream, CodegenError> {
    source
        .parse()
        .map_err(CodegenError::invalid_type(source.to_owned()))
}

fn rust_value(source: &str) -> Result<TokenStream, CodegenError> {
    source
        .parse()
        .map_err(CodegenError::invalid_literal(source.to_owned()))
}

/// The integer backing an enum newtype.
fn enum_inner_type(name: &str) -> TokenStream {
    if name.ends_with('2') {
        quote!(u64)
    } else {
        quote!(u32)
    }
}

impl Emit for VkEnums {
    fn emit(&self, emitter: &mut Emitter) -> Result<TokenStream, CodegenError> {
        match self {
            Self::ApiConstants { members } => {
                let members = members
                    .iter()
                    .map(|member| member.emit(emitter))
                    .collect::<Result<Vec<_>, _>>()?;
                Ok(quote!(#(#members)*))
            }
            Self::Enum { name, members } => {
                let inner = enum_inner_type(name);
                let name = format_ident!("{name}");
                let enumerators = members
                    .iter()
                    .filter(|member| {
                        matches!(
                            member,
                            VkEnumsMember::MemberValue { .. } | VkEnumsMember::MemberBitpos { .. }
                        )
                    })
                    .map(|member| member.emit(emitter))
                    .collect::<Result<Vec<_>, _>>()?;
                let aliases = members
                    .iter()
                    .filter(|member| matches!(member, VkEnumsMember::Alias { .. }))
                    .map(|member| member.emit(emitter))
                    .collect::<Result<Vec<_>, _>>()?;

                Ok(quote! {
                    #[derive(Debug, Eq, PartialEq, Copy, Clone)]
                    #[repr(transparent)]
                    pub struct #name(pub #inner);

                    impl #name {
                        #(#enumerators)*
                        #(#aliases)*
                    }

                    impl std::ops::BitOr for #name {
                        type Output = Self;

                        #[inline]
                        fn bitor(self, rhs: Self) -> Self::Output {
                            Self(self.0 | rhs.0)
                        }
                    }

                    impl std::ops::BitAnd for #name {
                        type Output = Self;

                        #[inline]
                        fn bitand(self, rhs: Self) -> Self::Output {
                            Self(self.0 & rhs.0)
                        }
                    }

                    impl PartialEq<#inner> for #name {
                        fn eq(&self, other: &#inner) -> bool {
                            self.0 == *other
                        }
                    }

                    impl From<#name> for #inner {
                        #[inline]
                        fn from(value: #name) -> Self {
                            value.0
                        }
                    }

                    impl From<#inner> for #name {
                        #[inline]
                        fn from(value: #inner) -> Self {
                            Self(value)
                        }
                    }
                })
            }
        }
    }
}

impl Emit for VkEnumsMember {
    fn emit(&self, emitter: &mut Emitter) -> Result<TokenStream, CodegenError> {
        match self {
            Self::ApiConstantMember { name, type_, value } => {
                emitter
                    .api_constant_types
                    .insert(Arc::clone(name), type_.0.clone());
                let name = format_ident!("{name}");
                let type_ = rust_type(&type_.0)?;
                let value = rust_value(value)?;
                let type_name = format_ident!("_{name}_type");
                Ok(quote! {
                    pub const #name: #type_ = #value;
                    pub type #type_name = #type_;
                })
            }
            Self::ApiConstantAlias { name, alias } => {
                let name = format_ident!("{name}");
                let alias = format_ident!("{alias}");
                let type_name = format_ident!("_{alias}_type");
                Ok(quote!(pub const #name: #type_name = #alias;))
            }
            Self::MemberValue {
                name,
                value: Some(value),
                enum_name,
            } => {
                let name = format_ident!("{name}");
                let inner = enum_inner_type(enum_name);
                let value = parse_int::parse::<i64>(value)
                    .map_err(|_| CodegenError::InvalidInteger(value.clone()))?;
                let value = Literal::i64_suffixed(value);
                Ok(quote!(pub const #name: Self = Self(#value as #inner);))
            }
            Self::MemberValue {
                name, value: None, ..
            } => {
                let name = format_ident!("{name}");
                Ok(quote!(#name,))
            }
            Self::MemberBitpos {
                name,
                bitpos,
                enum_name: _,
            } => {
                let name = format_ident!("{name}");
                let bitpos = parse_int::parse::<usize>(bitpos)
                    .map_err(|_| CodegenError::InvalidInteger(bitpos.to_string()))?;
                let bitpos = Literal::usize_unsuffixed(bitpos);
                Ok(quote!(pub const #name: Self = Self(1 << #bitpos);))
            }
            Self::Alias { name, alias, .. } => {
                let name = format_ident!("{name}");
                let alias = format_ident!("{alias}");
                Ok(quote!(pub const #name: Self = Self::#alias;))
            }
        }
    }
}

impl Emit for VkStruct {
    fn emit(&self, emitter: &mut Emitter) -> Result<TokenStream, CodegenError> {
        match self {
            Self::Alias { name, alias } => {
                let name = format_ident!("{name}");
                let alias = format_ident!("{alias}");
                Ok(quote!(pub type #name = #alias;))
            }
            Self::Struct { name, members } => {
                let ident = format_ident!("{name}");
                let members = members
                    .iter()
                    .map(|member| member.emit(emitter))
                    .collect::<Result<Vec<_>, _>>()?;
                Ok(quote! {
                    #[repr(C)]
                    #[derive(Debug, Copy, Clone)]
                    pub struct #ident {
                        #(#members)*
                    }

                    impl Default for #ident {
                        fn default() -> Self {
                            // SAFETY: Vulkan structs are plain-old-data C
                            // structs. Every field accepts an all-zero bit
                            // pattern: integers, floats, raw pointers,
                            // function pointers, nested POD structs, and
                            // nullable handles all have a valid zero value.
                            unsafe { std::mem::zeroed() }
                        }
                    }
                })
            }
            Self::Union { name, members } => {
                let ident = format_ident!("{name}");
                let members = members
                    .iter()
                    .map(|member| member.emit(emitter))
                    .collect::<Result<Vec<_>, _>>()?;
                Ok(quote! {
                    #[repr(C)]
                    #[derive(Copy, Clone)]
                    pub union #ident {
                        #(#members)*
                    }

                    impl std::fmt::Debug for #ident {
                        fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                            f.debug_struct(stringify!(#ident)).finish()
                        }
                    }

                    impl Default for #ident {
                        fn default() -> Self {
                            // SAFETY: A union has no invalid bit patterns at
                            // the type level; zero is a valid byte pattern and
                            // its fields are only read inside `unsafe` code.
                            unsafe { std::mem::zeroed() }
                        }
                    }
                })
            }
        }
    }
}

impl Emit for VkStructMember {
    fn emit(&self, _emitter: &mut Emitter) -> Result<TokenStream, CodegenError> {
        match self {
            Self::Member {
                name,
                type_,
                in_union,
            } => {
                let name = format_ident!("{name}");
                let type_ = if *in_union {
                    format!("std::mem::ManuallyDrop<{}>", type_.0)
                } else {
                    type_.0.clone()
                };
                let type_ = rust_type(&type_)?;
                Ok(quote!(pub #name: #type_,))
            }
        }
    }
}

