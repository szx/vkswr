    #[test]
    fn formats_cover_vk_format_enum() {
        let vk_xml = vk_xml();
        let formats: HashSet<&str> = vk_xml
            .formats
            .iter()
            .map(|format| format.name.as_ref())
            .collect();
        let mut enum_names = HashSet::new();

        for enums in &vk_xml.enums {
            let VkEnums::Enum { name, members } = enums else {
                continue;
            };
            if name.as_ref() != "VkFormat" {
                continue;
            }
            for member in members {
                if let VkEnumsMember::MemberValue { name, value, .. } = member
                    && value.is_some()
                {
                    enum_names.insert(name.as_ref());
                }
            }
        }

        for extension in &vk_xml.extensions {
            for member in &extension.enum_members {
                match member {
                    VkExtensionEnumMember::Value {
                        name,
                        extends: Some(extends),
                        ..
                    }
                    | VkExtensionEnumMember::ExtendsOffset { name, extends, .. }
                        if extends.as_ref() == "VkFormat" =>
                    {
                        enum_names.insert(name.as_ref());
                    }
                    _ => {}
                }
            }
        }

        for name in enum_names {
            assert!(
                name == "VK_FORMAT_UNDEFINED" || formats.contains(name),
                "{name} is missing from <formats>"
            );
        }
    }

