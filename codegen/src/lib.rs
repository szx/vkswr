impl Emit for VkExtension {
    fn emit(&self, emitter: &mut Emitter) -> Result<TokenStream, CodegenError> {
        let mut tokens = TokenStream::new();
        if !self.internal
            && !self.name.contains("VK_VERSION")
            && !self.name.contains("VKSC_VERSION")
        {
            let number_name = format_ident!("{}_NUMBER", self.name.to_uppercase());
            let number = rust_value(&self.number)?;
            tokens.extend(quote!(pub const #number_name: u64 = #number;));
        }
        for member in &self.enum_members {
            tokens.extend(member.emit(emitter)?);
        }
        Ok(tokens)
    }
}

impl Emit for VkExtensionEnumMember {
    fn emit(&self, emitter: &mut Emitter) -> Result<TokenStream, CodegenError> {
        match self {
            Self::Value {
                name,
                value,
                extends,
            } => {
                if !emitter.mark_seen_arc(name) {
                    return Ok(TokenStream::new());
                }
                let name = format_ident!("{name}");
                if let Some(extends) = extends {
                    let inner = enum_inner_type(extends);
                    let extends = format_ident!("{extends}");
                    // A plain `-5 as u32` still negates a `u32` literal, so
                    // give negative values an explicit signed type first.
                    let value = match parse_int::parse::<i64>(value) {
                        Ok(value) => {
                            let value = Literal::i64_suffixed(value);
                            quote!((#value) as #inner)
                        }
                        Err(_) => {
                            let value = rust_value(value)?;
                            quote!((#value) as #inner)
                        }
                    };
                    Ok(quote! {
                        impl #extends {
                            pub const #name: Self = Self(#value);
                        }
                    })
                } else {
                    let type_ = extension_value_type(value);
                    let value = rust_value(value)?;
                    Ok(quote!(pub const #name: #type_ = #value;))
                }
            }
            Self::Alias { name, alias } => {
                if !emitter.mark_seen_arc(name) {
                    return Ok(TokenStream::new());
                }
                let type_ = emitter
                    .api_constant_types
                    .get(alias.as_ref())
                    .cloned()
                    .unwrap_or_else(|| {
                        if name.ends_with("_NAME") {
                            "&str"
                        } else {
                            "isize"
                        }
                        .to_owned()
                    });
                let type_ = rust_type(&type_)?;
                let name = format_ident!("{name}");
                let alias = format_ident!("{alias}");
                Ok(quote!(pub const #name: #type_ = #alias;))
            }
            Self::ExtendsOffset {
                name,
                number,
                extends,
            } => {
                if !emitter.mark_seen_arc(name) {
                    return Ok(TokenStream::new());
                }
                let name = format_ident!("{name}");
                let number = Literal::isize_unsuffixed(*number);
                let extends = format_ident!("{extends}");
                Ok(quote! {
                    impl #extends {
                        pub const #name: Self = Self(#number);
                    }
                })
            }
            Self::ExtendsBitpos {
                name,
                bitpos,
                extends,
            } => {
                if !emitter.mark_seen_arc(name) {
                    return Ok(TokenStream::new());
                }
                let name = format_ident!("{name}");
                let bitpos = parse_int::parse::<usize>(bitpos)
                    .map_err(|_| CodegenError::InvalidInteger(bitpos.to_string()))?;
                let bitpos = Literal::usize_unsuffixed(bitpos);
                let extends = format_ident!("{extends}");
                Ok(quote! {
                    impl #extends {
                        pub const #name: Self = Self(1 << #bitpos);
                    }
                })
            }
            Self::ExtendsAlias {
                name,
                alias,
                extends,
            } => {
                if !emitter.mark_seen_arc(name) {
                    return Ok(TokenStream::new());
                }
                let name = format_ident!("{name}");
                let alias = format_ident!("{alias}");
                let extends = format_ident!("{extends}");
                Ok(quote! {
                    impl #extends {
                        pub const #name: Self = Self::#alias;
                    }
                })
            }
        }
    }
}

fn extension_value_type(value: &str) -> TokenStream {
    if value.starts_with('"') {
        quote!(&str)
    } else {
        quote!(isize)
    }
}

