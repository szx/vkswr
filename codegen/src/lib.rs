impl Emit for VkTypeExtern {
    fn emit(&self, emitter: &mut Emitter) -> Result<TokenStream, CodegenError> {
        match self {
            Self::Extern { name } => {
                if !emitter.mark_seen_arc(name) {
                    return Ok(TokenStream::new());
                }
                let name = format_ident!("{name}");
                Ok(quote!(pub type #name = VkUnsupportedType;))
            }
            Self::FuncPointer {
                type_,
                name,
                members,
            } => {
                let name = format_ident!("{name}");
                let members = members
                    .iter()
                    .map(|member| member.emit(emitter))
                    .collect::<Result<Vec<_>, _>>()?;
                Ok(match type_ {
                    Some(type_) => {
                        let type_ = rust_type(&type_.0)?;
                        quote!(pub type #name = Option<unsafe extern "C" fn(#(#members)*) -> #type_>;)
                    }
                    None => {
                        quote!(pub type #name = Option<unsafe extern "C" fn(#(#members)*)>;)
                    }
                })
            }
        }
    }
}

